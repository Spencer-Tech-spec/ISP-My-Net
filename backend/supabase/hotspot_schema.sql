-- ================================================================

-- 1. Ensure mikrotik_routers has all necessary hotspot columns
ALTER TABLE IF EXISTS mikrotik_routers
    ADD COLUMN IF NOT EXISTS router_type TEXT DEFAULT 'MikroTik',
    ADD COLUMN IF NOT EXISTS location TEXT,
    ADD COLUMN IF NOT EXISTS hotspot_name TEXT DEFAULT 'MyNet Hotspot',
    ADD COLUMN IF NOT EXISTS dns_name TEXT DEFAULT 'hotspot.mynet.local',
    ADD COLUMN IF NOT EXISTS portal_link TEXT,
    ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'active',
    ADD COLUMN IF NOT EXISTS is_online BOOLEAN DEFAULT true;

-- 2. Hotspot Packages Table
CREATE TABLE IF NOT EXISTS hotspot_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price INT NOT NULL,
    duration_label TEXT NOT NULL,       -- e.g. "1 Hour", "12 Hours", "24 Hours", "7 Days", "30 Days"
    duration_minutes INT NOT NULL,     -- duration in minutes
    speed_limit TEXT DEFAULT '5M/5M',  -- Rx/Tx limit e.g. 5M/5M
    data_limit_mb INT DEFAULT 0,       -- 0 = Unlimited
    device_limit INT DEFAULT 1,
    router_id BIGINT REFERENCES mikrotik_routers(id) ON DELETE SET NULL,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

