-- 3. Hotspot Vouchers Table
CREATE TABLE IF NOT EXISTS hotspot_vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    router_id BIGINT REFERENCES mikrotik_routers(id) ON DELETE SET NULL,
    router_name TEXT,
    package_id BIGINT REFERENCES hotspot_packages(id) ON DELETE SET NULL,
    package_name TEXT NOT NULL,
    price INT NOT NULL,
    phone_number TEXT NOT NULL,
    mpesa_receipt TEXT,
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'used', 'expired', 'rescued', 'pending')),
    duration_minutes INT NOT NULL,
    speed_limit TEXT DEFAULT '5M/5M',
    allocated_by TEXT DEFAULT 'system',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    expires_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ
);

-- Indexes for fast voucher lookup
CREATE INDEX IF NOT EXISTS idx_hotspot_vouchers_code ON hotspot_vouchers(code);
CREATE INDEX IF NOT EXISTS idx_hotspot_vouchers_phone ON hotspot_vouchers(phone_number);
CREATE INDEX IF NOT EXISTS idx_hotspot_vouchers_router ON hotspot_vouchers(router_id);
CREATE INDEX IF NOT EXISTS idx_hotspot_vouchers_status ON hotspot_vouchers(status);

-- Enable RLS
ALTER TABLE IF EXISTS hotspot_packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS hotspot_vouchers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view active packages" ON hotspot_packages;
CREATE POLICY "Public can view active packages" ON hotspot_packages FOR SELECT USING (is_active = true);

DROP POLICY IF EXISTS "Admins can manage packages" ON hotspot_packages;
CREATE POLICY "Admins can manage packages" ON hotspot_packages FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public can view their own vouchers" ON hotspot_vouchers;
CREATE POLICY "Public can view their own vouchers" ON hotspot_vouchers FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admins can manage vouchers" ON hotspot_vouchers;
CREATE POLICY "Admins can manage vouchers" ON hotspot_vouchers FOR ALL USING (true) WITH CHECK (true);
